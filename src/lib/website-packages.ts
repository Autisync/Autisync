/** "Kz 495.000", "£1,490", "€1.690" — each written the way that market reads it.
 *  Grouped by hand so server and browser render identically (no locale data drift). */
const group = (n: number, sep: string) => String(Math.round(n)).replace(/\B(?=(\d{3})+(?!\d))/g, sep);

export function formatPrice(amount: number, currency: Currency): string {
    switch (currency) {
        case "AOA":
            return `Kz ${group(amount, ".")}`;
        case "GBP":
            return `£${group(amount, ",")}`;
        case "EUR":
            return `€${group(amount, ".")}`;
    }
}

/** Best guess at the visitor's market from their time zone; Angola is the default. */
export function guessCurrency(): Currency {
    try {
        const tz = Intl.DateTimeFormat().resolvedOptions().timeZone || "";
        if (tz === "Europe/London" || tz === "Europe/Belfast") return "GBP";
        if (tz.startsWith("Europe/") || tz.startsWith("Atlantic/Azores") || tz.startsWith("Atlantic/Madeira")) return "EUR";
    } catch {
        /* fall through */
    }
    return "AOA";
}
